function buildDescription(seed: Seed): string {
  const cat = CATEGORIES.find((c) => c.slug === seed.category);
  return (
    `${seed.title.split(",")[0]} by ${seed.brand}. ` +
    `${seed.features[0]}. ${seed.features[1]}. ` +
    `A customer favourite in ${cat?.name ?? "our store"} with ` +
    `${seed.reviews.toLocaleString("en-US")} ratings — backed by Shopora's 30-day ` +
    `no-questions return policy and ${seed.brand} warranty support.`
  );
}

function buildSpecifications(seed: Seed, h: number): Record<string, string> {
  const cat = CATEGORIES.find((c) => c.slug === seed.category);
  const sub = cat?.subcategories.find((s) => s.slug === seed.sub);
  const weight = (0.2 + (h % 90) / 10).toFixed(1);
  const dims = `${6 + (h % 9)} x ${4 + (h % 7)} x ${2 + (h % 5)} inches`;
  return {
    Brand: seed.brand,
    "Model number": seed.id.toUpperCase().replace(/-/g, "").slice(0, 10),
    Department: `${cat?.name ?? ""} › ${sub?.name ?? ""}`,
    "Item weight": `${weight} pounds`,
    "Package dimensions": dims,
    "Country of origin": pick(["USA", "Vietnam", "Germany", "South Korea", "Japan"], h),
    Warranty: pick(["1-year limited", "2-year limited", "90-day limited"], h >> 3),
    "Date first listed": new Date(listedAtFor(h)).toLocaleDateString("en-US", {
      year: "numeric",
      month: "long",
    }),
  };
}

function listedAtFor(h: number): string {
  // Deterministic listing date in the ~18 months before the demo epoch.
  const day = h % 540;
  const d = new Date(Date.UTC(2026, 8, 1));
  d.setUTCDate(d.getUTCDate() - day);
  return d.toISOString();
}

function expand(seed: Seed): Product {
  const h = hashString(seed.id);
  const availability: Availability = OUT_OF_STOCK.has(seed.id)
    ? "out_of_stock"
    : LOW_STOCK.has(seed.id)
      ? "low_stock"
      : "in_stock";
  const stockCount =
    availability === "out_of_stock" ? 0 : availability === "low_stock" ? 2 + (h % 7) : 25 + (h % 200);
  const discount = seed.op ? Math.round(((seed.op - seed.price) / seed.op) * 100) : undefined;
  return {
    id: seed.id,
    title: seed.title,
    brand: seed.brand,
    description: buildDescription(seed),
    price: seed.price,
    originalPrice: seed.op,
    discount,
    rating: seed.rating,
    reviewCount: seed.reviews,
    images: [1, 2, 3].map((v) => `/api/placeholder/${seed.id}/${v}`),
    category: seed.category,
    subcategory: seed.sub,
    badges: seed.badges ?? [],
    availability,
    stockCount,
    seller: seed.price > 500 ? SELLERS[0] : SELLERS[h % SELLERS.length],
    deliveryInfo: {
      freeShipping: seed.price >= 25,
      express: h % 3 !== 0,
      estimatedDaysMin: 1 + (h % 3),
      estimatedDaysMax: 3 + (h % 3),
    },
    features: seed.features,
    specifications: buildSpecifications(seed, h),
    emoji: seed.emoji,
    listedAt: listedAtFor(h),
  };
}

export const PRODUCTS: Product[] = SEEDS.map(expand);

const BY_ID = new Map(PRODUCTS.map((p) => [p.id, p]));

export function getProductById(id: string): Product | undefined {
  return BY_ID.get(id);
}

export function getProductsByIds(ids: string[]): Product[] {
  return ids.map((id) => BY_ID.get(id)).filter((p): p is Product => Boolean(p));
}
